from e2e import *
h, a, b = three("47331")
# play a little so the save is not the opening position: everyone ends a turn
for s in (h, a, b): settle(s); s.click(*END_TURN)
h.wait(lambda st: int(st["turns"]) >= 1, "a season passes", 240)
for s in (h, a, b): settle(s)
time.sleep(2); note(f"G: turns {h.status()['turns']}")
h.shot("G4-host-before-end")
settle(h); h.click(*FILE); time.sleep(0.5); h.click(*HOST_END_ITEM); time.sleep(0.6); h.click(*LEAVE_BOX["save_end"])
h.wait(lambda st: st["screens"] == "[Setup(Title)]", "host at title", 20)
note(f"G: host saves: {sorted(os.listdir(h.saves))}")
for s in (a, b): s.kill()
h.click(320, 103); time.sleep(0.8); h.click(320, 138); time.sleep(1)
note(f"G: load a game -> {h.status()['screens']}"); h.shot("G5-load-list")
h.click(416, 90); time.sleep(3)
note(f"G: after load -> {h.status()['screens']} turns={h.status()['turns']} phase={h.status()['phase']}")
settle(h); h.shot("G6-loaded")
t = int(h.status()["turns"]); h.click(*END_TURN)
h.wait(lambda st: int(st["turns"]) > t, "the loaded game plays a season", 240)
note(f"G: loaded game plays on, turns {t} -> {h.status()['turns']}")
h.kill()
